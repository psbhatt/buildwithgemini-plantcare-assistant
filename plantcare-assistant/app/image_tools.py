import re
import uuid
from typing import Any, Dict
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

BUCKET_NAME = "flora-plantcare-media-f2446fdf"
PROJECT_ID = "qwiklabs-gcp-04-f2446fdf298c"
MODEL_NAME = "gemini-3.1-flash-lite-image"
LOCATION = "global"

async def generate_plant_image(
    plant_name_or_species: str,
    prompt_description: str,
    tool_context: ToolContext
) -> Dict[str, Any]:
    """Generate an image for a plant in Flora's collection or care domain using gemini-3.1-flash-lite-image.
    The generated image is saved as an artifact in the local playground AND uploaded to the public Cloud Storage bucket.

    Args:
        plant_name_or_species: Name or species of the plant (e.g. 'Monstera Deliciosa', 'Snake Plant', 'Monty').
        prompt_description: Detailed visual prompt describing the scene, leaf condition, or care setup.
        tool_context: ToolContext injected by the agent runtime for artifact management.

    Returns:
        A dictionary with the public image URL, bucket details, and confirmation message.
    """
    # 1. Initialize client in global location with Vertex AI
    client = genai.Client(vertexai=True, project=PROJECT_ID, location=LOCATION)

    full_prompt = (
        f"A beautiful, detailed, high-resolution botanical photograph of {plant_name_or_species}. "
        f"{prompt_description}"
    )

    response = client.models.generate_content(
        model=MODEL_NAME,
        contents=full_prompt,
        config=types.GenerateContentConfig(
            response_modalities=[types.Modality.IMAGE]
        )
    )

    # 2. Extract image bytes and mime type
    image_part = None
    if response.candidates and response.candidates[0].content and response.candidates[0].content.parts:
        for part in response.candidates[0].content.parts:
            if part.inline_data:
                image_part = part
                break

    if not image_part or not image_part.inline_data:
        return {"error": "No image data was generated by the model."}

    image_bytes = image_part.inline_data.data
    mime_type = image_part.inline_data.mime_type or "image/jpeg"
    ext = "jpg" if "jpeg" in mime_type else "png"

    clean_slug = re.sub(r"[^a-z0-9_-]", "", plant_name_or_species.lower().replace(" ", "-"))
    unique_id = uuid.uuid4().hex[:8]
    filename = f"{clean_slug}-{unique_id}.{ext}"

    # 3. Save as artifact in Playground
    artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
    await tool_context.save_artifact(filename=filename, artifact=artifact_part)

    # 4. Upload bytes directly to Cloud Storage (no local file written)
    storage_client = storage.Client(project=PROJECT_ID)
    bucket = storage_client.bucket(BUCKET_NAME)
    blob = bucket.blob(filename)
    blob.upload_from_string(image_bytes, content_type=mime_type)

    public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/{filename}"

    return {
        "status": "success",
        "plant": plant_name_or_species,
        "filename": filename,
        "public_url": public_url,
        "message": f"Image generated and uploaded to Cloud Storage: {public_url}"
    }
